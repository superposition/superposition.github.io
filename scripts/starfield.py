"""Generate assets/art/starfield.svg: a seamless star field for the poster identity.

Deterministic (fixed seed), so the committed SVG and this script cannot drift.
Stars keep a margin from the tile edge and the tile is used with
background-repeat, so it tiles without seams.

    python scripts/starfield.py
"""

import random
from pathlib import Path

W, H = 1200, 800
MARGIN = 6
SEED = 1977
OUT = Path(__file__).resolve().parent.parent / "assets" / "art" / "starfield.svg"

STAR = "#eef3ff"


def main() -> None:
    rng = random.Random(SEED)
    stars = []
    for _ in range(220):
        x = round(rng.uniform(MARGIN, W - MARGIN), 1)
        y = round(rng.uniform(MARGIN, H - MARGIN), 1)
        r = round(rng.choice([0.55, 0.7, 0.7, 0.9, 0.9, 1.1, 1.4, 1.9]), 2)
        o = round(rng.choice([0.35, 0.45, 0.55, 0.7, 0.85, 1.0]), 2)
        stars.append((x, y, r, o))

    body = "\n".join(
        f'<circle cx="{x}" cy="{y}" r="{r}" opacity="{o}"/>' for x, y, r, o in stars
    )
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" '
        f'viewBox="0 0 {W} {H}" fill="{STAR}">\n'
        f"<!-- Generated by scripts/starfield.py. Seed {SEED}, {len(stars)} stars, "
        f"tileable. Not decoration: it is the ground of the poster identity. -->\n"
        f"{body}\n</svg>\n"
    )
    with OUT.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(svg)
    print(f"{OUT} {OUT.stat().st_size} bytes, {len(stars)} stars")


if __name__ == "__main__":
    main()
